create extension if not exists pgcrypto;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text,
  items text not null,
  total numeric(12,2) check (total is null or total >= 0),
  status text not null default 'pendiente' check (status in ('pendiente', 'confirmado', 'preparando', 'listo', 'entregado', 'cancelado')),
  ordered_at date not null default current_date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_ordered_at_idx on public.orders (ordered_at desc);
create index if not exists orders_status_idx on public.orders (status);

alter table public.orders enable row level security;

